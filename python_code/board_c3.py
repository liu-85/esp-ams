"""
board_c3.py —— ESP32-C3 板型配置（引脚 / 保留脚 / strapping）
=============================================================

本文件只描述**这块芯片本身**的引脚能力，不含业务参数
（动作时长、离合等待时间那些在 hardware_config.py 里）。
换板子改的是这一层，改业务改的是 hardware_config.py。

★ 引脚编号表（ESP32-C3，GPIO0 ~ GPIO21 共 22 个）：

      ┌──────────┬──────────────────────────────────────────────┐
      │ GPIO     │ 能不能拿来做输出                              │
      ├──────────┼──────────────────────────────────────────────┤
      │ 0, 1     │ ✅ 干净，推荐                                  │
      │ 2, 3     │ ⚠️ strapping（GPIO3 还是 JTAG 源选择脚）        │
      │ 4 ~ 7    │ ✅ 干净（默认 JTAG，但做普通 IO 没问题）        │
      │ 8, 9     │ ⚠️ strapping                                   │
      │ 10       │ ✅ 干净                                        │
      │ 11 ~ 17  │ ❌ 模组内置 SPI Flash（SPI0/1 / VDD_SPI）      │
      │ 18, 19   │ ❌ USB D- / D+                                 │
      │ 20, 21   │ ❌ UART0 RX / TX（REPL 与日志口）              │
      └──────────┴──────────────────────────────────────────────┘

★★★ 为什么 strapping 脚不能拿来驱动电机 / 离合 ★★★

    参与 Boot 模式采样的是 **四个**脚：GPIO2、GPIO3、GPIO8、GPIO9
    （《ESP32-C3 技术参考手册》第 7 章表 7.2-1）。其中只有 GPIO9 带内部
    弱上拉，GPIO2 / GPIO3 / GPIO8 复位后是**浮空**的 —— 外部接什么就是什么。

    AT8236 的 IN1/IN2 内置下拉电阻、ULN2803 输入是达林顿基极（低阻），
    把这类负载挂上 strapping 脚，上电瞬间就会把它拉低 → 芯片进不了正常
    启动模式 → 典型现象：反复复位、串口来回刷、WiFi 和网页永远起不来，
    同时 H 桥跟着"叫"。

    所以：
      · 电机 IN1/IN2、离合、状态灯 —— 只能用 SAFE_OUTPUT_PINS 里的脚
      · strapping 脚作**输入**（内部上拉 + 开关对地）是安全的，空闲为高
      · GPIO2 留给板载 LED 是可以的（LED 低电平时不导通，呈高阻）

--------------------------------------------------------------------------
C3 的现实约束（这也是本方案在 C3 上"带病运行"的地方）
--------------------------------------------------------------------------
    C3 只有 7 只干净脚（SAFE_OUTPUT_PINS），而本方案需要
    "电机 2 只 + 离合 4 只" = 6 只，加上状态灯就正好 7 只，
    **一只都不剩**，没法再给到位开关留位置。

    当前默认把 4 号离合放在 GPIO3（strapping）上，属于"带病运行"：
    ULN2803 空闲时接近高阻所以现在能用，但换用输入带下拉的驱动板就会起不来。
    如果坚持用 C3，建议把 4 号离合挪到 GPIO1：
        CLUTCH_PINS = (6, 7, 10, 1)
    然后用 GPIO0 / GPIO3 当到位开关（作输入是安全的）。

    ⚠️ 另一条 C3 的硬伤：SRAM 只有 400KB，本应用加载完只剩约 60KB 空闲，
       WiFi 驱动收发大数据时会因为申请不到连续缓冲而报错（实测：网页传
       65KB 的 index.html 传不完、射频卡死）。**要稳就跑 ESP32-S3**
       （SRAM 512KB + 可选 PSRAM，见 board_s3.py）。
"""

BOARD_ID = "c3"
BOARD_NAME = "ESP32-C3（22 个 GPIO 的经典小板）"
CHIP = "esp32c3"

# os.uname().machine 里出现下面任一关键字就认定为这块板
# （实测 C3 上形如 "ESP32C3 module with ESP32C3"）
MACHINE_KEYWORDS = ("ESP32C3", "ESP32-C3", "C3")

GPIO_MAX = 21

# ==========================================================================
# 默认接线（按需修改；改完记得重跑 tools/build_mpy.py）
# ==========================================================================
# ⚠️ 电机 IN1/IN2 不要改成 GPIO2 / GPIO3：AT8236 输入级内置下拉会把
#    strapping 脚在上电瞬间拉低，芯片进不了正常启动模式。
MOTOR_PIN_IN1 = 4        # H 桥 IN1，方向 1 = 进料（正转）
MOTOR_PIN_IN2 = 5        # H 桥 IN2，方向 -1 = 退料（反转）

# 通道 4 落在 GPIO3（strapping）上，能启动但属于"带病运行"，
# 想彻底干净就改成 (6, 7, 10, 1)（见文件头说明）。
CLUTCH_PINS = (6, 7, 10, 3)

LED_PIN = 2              # 板载蓝灯；None = 不用状态灯

# 到位开关默认未安装。装了以后从这些脚里挑（作输入安全）：
#     LIMIT_SWITCH_PINS = (0, 1, 8, 9)
LIMIT_SWITCH_PINS = (None, None, None, None)
RECOMMENDED_LIMIT_SWITCH_PINS = (0, 1, 8, 9)

# ==========================================================================
# 引脚分类（校验用）
# ==========================================================================
# 上电瞬间决定启动模式的脚：作输入安全，作输出危险
STRAPPING_PINS = (2, 3, 8, 9)

# 可以安全用作输出的脚（避开 Flash 11~17 / USB 18~19 / UART 20~21 / strapping）
SAFE_OUTPUT_PINS = (0, 1, 4, 5, 6, 7, 10)

# 完全不能用的脚：{GPIO: 原因}
RESERVED_PINS = {
    11: "模组内置 SPI Flash (SPI0/1)",
    12: "模组内置 SPI Flash (SPI0/1)",
    13: "模组内置 SPI Flash (SPI0/1)",
    14: "模组内置 SPI Flash (SPI0/1)",
    15: "模组内置 SPI Flash (SPI0/1)",
    16: "模组内置 SPI Flash (SPI0/1)",
    17: "模组内置 SPI Flash (SPI0/1)",
    18: "USB D-",
    19: "USB D+",
    20: "UART0 RX（REPL）",
    21: "UART0 TX（REPL）",
}

# 除已用之外、还能给用户接外设的干净脚（SAFE_OUTPUT_PINS 减去已占用的脚）
SPARE_PINS = (0, 1)

# 空闲的 strapping 脚：作**输入**（内部上拉 + 开关对地）安全；作输出危险
# （GPIO2 被状态灯占了、GPIO3 被 4 号离合占了，所以只剩这两只）
STRAPPING_SPARE_PINS = (8, 9)

# 每块板特有的整块说明，打印在自检里
BOARD_NOTES = (
    "C3 只有 7 只干净输出脚，本方案已用掉 7 只，没有多余干净脚给外设",
    "C3 空闲堆仅约 60KB，传大文件（网页 >30KB）时 WiFi 收发缓冲可能申请失败；建议改用 ESP32-S3",
)
